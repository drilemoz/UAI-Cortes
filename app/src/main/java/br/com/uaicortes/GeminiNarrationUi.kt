package br.com.uaicortes

import android.net.Uri
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.*
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.AutoAwesome
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import androidx.media3.common.MediaItem
import androidx.media3.common.Player
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import kotlinx.coroutines.ensureActive
import kotlin.coroutines.coroutineContext
import java.io.File

private val narrationStyles = linkedMapOf(
    "Neutra" to "clear, neutral and natural Brazilian Portuguese narration",
    "Jornalística" to "informative broadcast newsreader, deliberate and articulate",
    "Animada" to "cheerful, upbeat and expressive",
    "Calma" to "soft, relaxed and soothing",
    "Sussurrada" to "softly whispered, intimate"
)

@Composable
internal fun GeminiNarrationSection(project: VideoProject, timelinePositionMs: Long,
    update: (VideoProject) -> Unit, openSettings: () -> Unit) {
    val ctx = LocalContext.current
    val creds = remember(ctx) { GeminiCredentialStore(ctx) }
    val api = remember { GeminiTtsClient() }
    val scope = rememberCoroutineScope()
    var expanded by remember(project.id) { mutableStateOf(false) }
    var text by remember(project.id) { mutableStateOf("") }
    var model by remember { mutableStateOf(GeminiModels.LITE) }
    var selectedVoice by remember { mutableStateOf<GeminiVoice?>(null) }
    var voices by remember { mutableStateOf<List<GeminiVoice>>(emptyList()) }
    var style by remember { mutableStateOf("Neutra") }
    var status by remember { mutableStateOf("") }
    var loading by remember { mutableStateOf(false) }
    var working by remember { mutableStateOf(false) }
    var generated by remember(project.id) { mutableStateOf<File?>(null) }
    var duration by remember(project.id) { mutableLongStateOf(0L) }
    var addedUri by remember { mutableStateOf<String?>(null) }
    var preview by remember { mutableStateOf<File?>(null) }
    var confirmation by remember { mutableStateOf("") }
    var voiceMenu by remember { mutableStateOf(false) }
    var modelMenu by remember { mutableStateOf(false) }
    var styleMenu by remember { mutableStateOf(false) }
    var job by remember { mutableStateOf<Job?>(null) }
    val lastPreview by rememberUpdatedState(preview)
    val lastJob by rememberUpdatedState(job)
    val player = remember(ctx) { diagnosticPlayer(ctx) }
    var playing by remember { mutableStateOf(false) }
    DisposableEffect(player, api) {
        val listener = object : Player.Listener {
            override fun onIsPlayingChanged(isPlaying: Boolean) { playing = isPlaying }
        }
        player.addListener(listener)
        onDispose {
            api.cancel(); lastJob?.cancel()
            player.removeListener(listener); player.release(); lastPreview?.delete()
        }
    }
    val savePicker = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("audio/wav")) { uri ->
        val localFile = generated
        if (uri != null && localFile != null) scope.launch {
            working = true
            try {
                withContext(Dispatchers.IO) {
                    ctx.contentResolver.openOutputStream(uri, "wt")?.use { dest ->
                        localFile.inputStream().use { it.copyTo(dest) }
                        dest.flush()
                    } ?: throw java.io.IOException("Destino indisponível")
                }
                status = "Narração salva no local selecionado."
            } catch (_: Exception) { status = "Não foi possível salvar o arquivo de áudio." }
            finally { working = false }
        }
    }
    fun loadVoices() {
        if (loading || working) return
        job = scope.launch {
            loading = true
            try {
                val key = withContext(Dispatchers.IO) { creds.read() }
                    ?: throw IllegalStateException("Configure sua chave Gemini.")
                val available = api.voices(key)
                voices = available
                selectedVoice = available.firstOrNull { it.id == selectedVoice?.id } ?: available.firstOrNull()
                status = if (available.isEmpty()) "Nenhuma voz em português brasileiro foi retornada para esta chave."
                    else "${available.size} vozes retornadas pelo catálogo oficial da sua chave."
            } catch (e: CancellationException) { throw e }
            catch (e: GeminiApiError) { status = e.message ?: "Erro ao consultar vozes." }
            catch (_: Exception) { status = "Não foi possível consultar as vozes. Confira a conexão e a chave." }
            finally { loading = false }
        }
    }
    Column(verticalArrangement = Arrangement.spacedBy(9.dp)) {
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
            Row { Icon(Icons.Default.AutoAwesome, null, tint = MaterialTheme.colorScheme.primary)
                Spacer(Modifier.width(8.dp)); Text("Narração com IA", style = MaterialTheme.typography.titleMedium) }
            TextButton(onClick = {
                expanded = !expanded
                if (expanded && creds.hasKey() && voices.isEmpty()) loadVoices()
            }) { Text(if (expanded) "Recolher" else "Abrir") }
        }
        if (expanded) {
            Text("A geração usa internet. Áudios salvos neste aplicativo funcionam offline.",
                style = MaterialTheme.typography.bodySmall)
            if (!creds.hasKey()) {
                Text("Nenhuma chave Gemini configurada.")
                Button(onClick = openSettings) { Text("Configurar Google Gemini") }
            } else {
                OutlinedTextField(value = text, onValueChange = { text = it.take(4000) },
                    modifier = Modifier.fillMaxWidth(), minLines = 4, maxLines = 9,
                    label = { Text("Texto da narração (pt-BR)") },
                    supportingText = { Text("${text.length}/4000 caracteres. Somente este texto será enviado.") })
                Box {
                    OutlinedButton(onClick = { modelMenu = true }, enabled = !working && !loading) {
                        Text(if (model == GeminiModels.LITE) "Gemini 3.8 Flash-Lite TTS" else "Gemini 3.8 Flash TTS")
                    }
                    DropdownMenu(expanded = modelMenu, onDismissRequest = { modelMenu = false }) {
                        GeminiModels.supported.forEach { option -> DropdownMenuItem(
                            text = { Text(if (option == GeminiModels.LITE) "Flash-Lite TTS" else "Flash TTS") },
                            onClick = { model = option; modelMenu = false }) }
                    }
                }
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Box(modifier = Modifier.weight(1f)) {
                        OutlinedButton(onClick = { voiceMenu = true }, enabled = !working && voices.isNotEmpty()) {
                            Text(selectedVoice?.name ?: "Sem voz disponível", maxLines = 1)
                        }
                        DropdownMenu(expanded = voiceMenu, onDismissRequest = { voiceMenu = false }) {
                            voices.forEach { voice -> DropdownMenuItem(
                                text = { Text("${voice.name} (${voice.id})") },
                                onClick = { selectedVoice = voice; voiceMenu = false }) }
                        }
                    }
                    TextButton(onClick = { loadVoices() }, enabled = !working && !loading) { Text("Atualizar vozes") }
                }
                selectedVoice?.description?.takeIf { it.isNotBlank() }?.let {
                    Text(it, style = MaterialTheme.typography.bodySmall)
                }
                Box {
                    OutlinedButton(onClick = { styleMenu = true }, enabled = !working) { Text("Estilo: $style") }
                    DropdownMenu(expanded = styleMenu, onDismissRequest = { styleMenu = false }) {
                        narrationStyles.keys.forEach { label -> DropdownMenuItem(text = { Text(label) },
                            onClick = { style = label; styleMenu = false }) }
                    }
                }
                Text("Os estilos são enviados em speech_metadata.style. O resultado vocal pode variar conforme a voz.",
                    style = MaterialTheme.typography.bodySmall)
                if (loading || working) {
                    LinearProgressIndicator(Modifier.fillMaxWidth())
                    Text(if (loading) "Consultando vozes..." else "Processando solicitação...",
                        style = MaterialTheme.typography.bodySmall)
                }
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Button(onClick = { confirmation = "generate" },
                        enabled = !working && !loading && text.isNotBlank() && selectedVoice != null) {
                        Text("Gerar áudio")
                    }
                    OutlinedButton(onClick = { confirmation = "sample" },
                        enabled = !working && !loading && selectedVoice != null) { Text("Prévia da voz") }
                }
                if (working) OutlinedButton(onClick = {
                    job?.cancel(); api.cancel(); status = "Operação cancelada. A solicitação pode já ter consumido cota."
                    working = false
                }) { Text("Cancelar") }
                generated?.let { file ->
                    if (file.exists()) {
                        Text("Narração gerada: ${duration / 1000}.${(duration % 1000) / 100} s")
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            OutlinedButton(onClick = {
                                val thisAudioPlaying = playing &&
                                    player.currentMediaItem?.localConfiguration?.uri == Uri.fromFile(file)
                                if (thisAudioPlaying) player.pause() else {
                                    if (player.currentMediaItem?.localConfiguration?.uri != Uri.fromFile(file) ||
                                        player.playbackState == Player.STATE_ENDED) {
                                        player.setMediaItem(MediaItem.fromUri(Uri.fromFile(file)))
                                        player.prepare()
                                    }
                                    player.play()
                                }
                            }, enabled = !working) { Text(if (playing && player.currentMediaItem?.localConfiguration?.uri == Uri.fromFile(file))
                                "Pausar" else "Reproduzir") }
                            OutlinedButton(onClick = { savePicker.launch("UaiCortes_narracao.wav") },
                                enabled = !working) { Text("Salvar áudio") }
                        }
                        Button(onClick = {
                            val available = (project.durationMs - timelinePositionMs.coerceIn(0L, project.durationMs))
                                .coerceAtLeast(0L)
                            val usable = minOf(duration, available)
                            if (usable < 250L) status = "Posicione o cursor antes do fim do projeto."
                            else {
                                val uri = GeminiAudioFiles.uri(file)
                                if (addedUri != uri && project.audioTracks.none { it.uri == uri }) {
                                    val track = AudioTrack(uri = uri, title = "Narração Gemini",
                                        startMs = timelinePositionMs.coerceIn(0L, project.durationMs),
                                        durationMs = usable, volume = 1f)
                                    update(project.copy(audioTracks = project.audioTracks + track))
                                    addedUri = uri
                                    status = if (usable < duration) "Narração adicionada. Final cortado no limite do vídeo."
                                        else "Narração adicionada à timeline. Use os controles de áudio para editar."
                                } else status = "Esta narração já foi adicionada ao projeto."
                            }
                        }, enabled = !working && (addedUri != GeminiAudioFiles.uri(file))) {
                            Text("Adicionar à timeline")
                        }
                    }
                }
                if (status.isNotBlank()) Text(status, style = MaterialTheme.typography.bodySmall)
            }
        }
    }
    if (confirmation.isNotBlank()) AlertDialog(onDismissRequest = { confirmation = "" },
        title = { Text("Confirmar solicitação Gemini") },
        text = { Text(if (confirmation == "sample") "A prévia sintetizará um texto curto e poderá consumir cota."
            else "Gerar esta narração pode consumir cota ou gerar cobrança. Não haverá repetição automática em caso de falha.") },
        confirmButton = { TextButton(onClick = {
            val action = confirmation; confirmation = ""
            if (working || loading) return@TextButton
            job = scope.launch {
                working = true
                status = "Solicitando áudio ao Gemini..."
                try {
                    val key = withContext(Dispatchers.IO) { creds.read() }
                        ?: throw IllegalStateException("Chave ausente")
                    val voice = selectedVoice ?: throw IllegalStateException("Nenhuma voz")
                    if (!api.checkModel(key, model)) throw GeminiApiError(404, "NOT_FOUND")
                    val input = if (action == "sample") "Olá! Esta é uma prévia da minha voz." else text.trim()
                    val wave = api.synthesize(key, model, voice.id, narrationStyles.getValue(style), input)
                    val file = withContext(Dispatchers.IO) {
                        coroutineContext.ensureActive()
                        val resultFile = if (action == "sample") {
                            val dest = File.createTempFile("gemini-voice-", ".wav", ctx.cacheDir)
                            try { dest.outputStream().use { it.write(wave.bytes) }; dest }
                            catch (e: Exception) { dest.delete(); throw e }
                        } else GeminiAudioFiles.save(ctx, wave)
                        try { coroutineContext.ensureActive(); resultFile }
                        catch (e: CancellationException) { resultFile.delete(); throw e }
                    }
                    if (action == "sample") {
                        preview?.delete(); preview = file
                    } else {
                        generated = file; duration = wave.durationMs; addedUri = null
                    }
                    player.setMediaItem(MediaItem.fromUri(Uri.fromFile(file)))
                    player.prepare()
                    if (action == "sample") player.play()
                    status = if (action == "sample") "Prévia sintetizada pela API e reproduzida."
                        else "Áudio gerado e salvo internamente."
                } catch (e: CancellationException) { status = "Solicitação cancelada."; throw e }
                catch (e: GeminiApiError) { status = e.message ?: "Falha na API Gemini." }
                catch (e: java.io.IOException) { status = e.message ?: "Falha de conexão ou armazenamento." }
                catch (_: Exception) { status = "Não foi possível gerar áudio ou acessar a chave." }
                finally { working = false }
            }
        }) { Text("Continuar") } },
        dismissButton = { TextButton(onClick = { confirmation = "" }) { Text("Voltar") } })
}
