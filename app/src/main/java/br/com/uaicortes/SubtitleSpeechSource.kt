package br.com.uaicortes

import android.content.Context
import android.net.Uri
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

internal data class SubtitleSpeechRange(val startMs: Long, val endMs: Long) {
    val durationMs get() = endMs - startMs
    fun contains(cue: SubtitleCue) = cue.startMs >= startMs && cue.endMs <= endMs
    fun touches(cue: SubtitleCue) = cue.startMs < endMs && cue.endMs > startMs
}

internal data class SubtitleSpeechSource(val project: VideoProject, val offsetMs: Long)

internal suspend fun prepareSubtitleSpeechSource(context: Context, project: VideoProject, track: AudioTrack?,
    range: SubtitleSpeechRange = SubtitleSpeechRange(0L, project.durationMs)): SubtitleSpeechSource =
    withContext(Dispatchers.IO) {
        if (track == null) {
            SubtitleSpeechSource(subtitleSpeechSlice(project, range), range.startMs)
        } else {
            require(range.startMs >= 0 && range.endMs <= project.durationMs && range.durationMs > 0)
            val duration = verifiedMediaDuration(context, Uri.parse(track.uri))
            val window = requireNotNull(ExportAudioPolicy.window(track.startMs, track.sourceStartMs,
                track.durationMs, duration, project.durationMs)) {
                "Não foi possível confirmar o trecho da narração."
            }
            val from = maxOf(range.startMs, window.timelineStartMs)
            val until = minOf(range.endMs, window.timelineStartMs + window.playableMs)
            require(until > from) { "A narração não toca no trecho selecionado." }
            val begin = window.sourceStartMs + from - window.timelineStartMs
            val clip = Clip(id = track.id, uri = track.uri, title = track.title, sourceDurationMs = duration,
                startMs = begin, endMs = begin + until - from)
            SubtitleSpeechSource(speechOnly(project, listOf(clip)), from)
        }
    }

internal fun subtitleSpeechSlice(project: VideoProject, range: SubtitleSpeechRange): VideoProject {
    require(range.startMs >= 0 && range.endMs <= project.durationMs && range.durationMs > 0)
    var next = 0L
    val clips = project.clips.mapNotNull { clip ->
        val projectStart = next
        next += clip.durationMs
        val start = maxOf(projectStart, range.startMs)
        val end = minOf(next, range.endMs)
        if (end <= start) null else clip.copy(startMs = clip.startMs + start - projectStart,
            endMs = clip.startMs + end - projectStart)
    }
    return speechOnly(project, clips)
}

private fun speechOnly(project: VideoProject, clips: List<Clip>) = project.copy(
    clips = clips, overlays = emptyList(), audioTracks = emptyList(), music = null, subtitles = emptyList(),
    transitions = emptyList(), textWatermark = null)

internal object SubtitleSpeechDraft {
    const val MAX_OPERATION_MS = 600_000L
    fun place(cues: List<SubtitleCue>, offset: Long, range: SubtitleSpeechRange): List<SubtitleCue> =
        cues.mapNotNull { cue ->
            val start = cue.startMs + offset
            val end = cue.endMs + offset
            if (start < range.startMs || end > range.endMs || end <= start) null
            else cue.copy(startMs = start, endMs = end, wordTimings = cue.wordTimings.map { word ->
                word.copy(startMs = word.startMs + offset, endMs = word.endMs + offset)
            })
        }

    /** Clip-window edits never remove subtitles that extend outside the chosen window. */
    fun redo(original: List<SubtitleCue>, generated: List<SubtitleCue>, range: SubtitleSpeechRange): List<SubtitleCue> {
        val keep = original.filterNot(range::contains)
        val accepted = mutableListOf<SubtitleCue>()
        for (cue in generated.sortedBy { it.startMs }) {
            if (range.contains(cue) && keep.none { it.startMs < cue.endMs && it.endMs > cue.startMs } &&
                (accepted.lastOrNull()?.endMs ?: Long.MIN_VALUE) <= cue.startMs) {
                // Speaker IDs generated by another request have no known relation to the current draft.
                accepted += cue.copy(speakerId = null)
            }
        }
        if (accepted.isEmpty()) return original
        val modified = original.filter { cue -> range.contains(cue) &&
            accepted.any { it.startMs < cue.endMs && it.endMs > cue.startMs } }.map { it.id }.toSet()
        return (original.filterNot { it.id in modified } + accepted).sortedBy { it.startMs }
    }
}
