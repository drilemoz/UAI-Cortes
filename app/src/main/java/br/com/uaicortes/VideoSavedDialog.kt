package br.com.uaicortes

import android.content.ClipData
import android.content.Intent
import android.graphics.Bitmap
import android.net.Uri
import android.os.Build
import android.util.Size
import androidx.compose.foundation.Image
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextOverflow
import androidx.compose.ui.unit.dp
import androidx.compose.ui.window.Dialog
import androidx.compose.ui.window.DialogProperties
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import java.io.IOException

/** Vídeo salvo no MediaStore: publicação opcional, sem modificar o arquivo exportado. */
@Composable
internal fun VideoSavedDialog(
    uri: Uri, name: String, editLabel: String,
    exportDetails: List<String> = emptyList(),
    qualityReport: ExportQualityReport? = null,
    videoContext: String = "",
    onEdit: () -> Unit, onClose: () -> Unit
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val generator = remember(uri) { GeminiVideoCaptionClient() }
    DisposableEffect(generator) { onDispose { generator.cancel() } }
    var failure by remember(uri) { mutableStateOf<String?>(null) }
    var description by remember(uri) { mutableStateOf("") }
    var hashtags by remember(uri) { mutableStateOf("") }
    var topic by remember(uri) { mutableStateOf("") }
    var showTopic by remember(uri) { mutableStateOf(videoContext.isBlank()) }
    var showDetails by remember(uri) { mutableStateOf(false) }
    var showGeminiConsent by remember(uri) { mutableStateOf(false) }
    var generating by remember(uri) { mutableStateOf(false) }
    var hasGenerated by remember(uri) { mutableStateOf(false) }
    var copied by remember(uri) { mutableStateOf(false) }

    val displayedName = remember(uri, name) {
        if (name.isNotBlank()) name else runCatching {
            context.contentResolver.query(uri,
                arrayOf(android.provider.MediaStore.MediaColumns.DISPLAY_NAME), null, null, null)
                ?.use { cursor -> if (cursor.moveToFirst()) cursor.getString(0) else null }
        }.getOrNull() ?: "UaiCortes_Animado.mp4"
    }
    val thumbnail by produceState<Bitmap?>(null, uri) {
        value = withContext(Dispatchers.IO) {
            if (Build.VERSION.SDK_INT >= 29) runCatching {
                context.contentResolver.loadThumbnail(uri, Size(320, 180), null)
            }.getOrNull() else null
        }
    }
    val chars = VideoCaptionPolicy.totalCharacters(description, hashtags)
    val tagCount = VideoCaptionPolicy.hashtagCount(hashtags)
    val captionValid = VideoCaptionPolicy.isValid(description, hashtags)
    // O conteúdo do vídeo não é lido pela IA: somente o texto mostrado ao usuário.
    val contextToSend = remember(videoContext, topic) {
        listOf(videoContext.trim().take(900), topic.trim().take(280))
            .filter { it.isNotBlank() }.joinToString("\n")
    }

    Dialog(onDismissRequest = onClose,
        properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Surface(Modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
            Column(Modifier.fillMaxSize().statusBarsPadding().navigationBarsPadding()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 18.dp, vertical = 16.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    Icon(Icons.Default.CheckCircle, null, Modifier.size(46.dp),
                        tint = MaterialTheme.colorScheme.primary)
                    Column {
                        Text("Vídeo salvo!", style = MaterialTheme.typography.headlineSmall,
                            fontWeight = FontWeight.Bold)
                        Text("Disponível na galeria do celular",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }

                Card(Modifier.fillMaxWidth()) {
                    Row(Modifier.padding(12.dp), horizontalArrangement = Arrangement.spacedBy(12.dp),
                        verticalAlignment = Alignment.CenterVertically) {
                        Box(Modifier.size(width = 104.dp, height = 76.dp)
                            .clip(RoundedCornerShape(10.dp))
                            .background(MaterialTheme.colorScheme.surfaceVariant),
                            contentAlignment = Alignment.Center) {
                            if (thumbnail != null) {
                                Image(thumbnail!!.asImageBitmap(), contentDescription = "Miniatura do vídeo salvo",
                                    modifier = Modifier.fillMaxSize(), contentScale = ContentScale.Crop)
                            } else Icon(Icons.Default.Movie, null, Modifier.size(36.dp),
                                tint = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                        Column(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(3.dp)) {
                            Text(displayedName, style = MaterialTheme.typography.titleSmall,
                                fontWeight = FontWeight.SemiBold, maxLines = 2,
                                overflow = TextOverflow.Ellipsis)
                            qualityReport?.let { report ->
                                Text(report.resolution + " · " + report.fileSize,
                                    style = MaterialTheme.typography.bodySmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant)
                                if (report.averageFps != "Não informado")
                                    Text("Quadros: ${report.averageFps}",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                            } ?: Text("Arquivo MP4", style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                    }
                    Row(Modifier.padding(start = 12.dp, end = 12.dp, bottom = 10.dp),
                        verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.Folder, null, Modifier.size(16.dp),
                            tint = MaterialTheme.colorScheme.onSurfaceVariant)
                        Spacer(Modifier.width(5.dp))
                        Text("Galeria / Filmes/UaiCortes",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }

                HorizontalDivider()
                Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Descrição para publicar", style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.SemiBold)
                    Text("Descrição na primeira linha e 5 hashtags na segunda. Tudo em até 100 caracteres, sem emojis.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                    OutlinedTextField(value = description,
                        onValueChange = { description = it; copied = false },
                        label = { Text("Descrição") }, placeholder = { Text("Descreva o vídeo...") },
                        modifier = Modifier.fillMaxWidth(), maxLines = 2,
                        singleLine = false,
                        isError = description.isNotEmpty() &&
                            (chars > VideoCaptionPolicy.MAX_CHARACTERS ||
                                VideoCaptionPolicy.containsEmoticonOrEmoji(description)))
                    Row(verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        OutlinedTextField(value = hashtags,
                            onValueChange = { hashtags = it; copied = false },
                            label = { Text("5 hashtags") },
                            placeholder = { Text("#UaiCortes #Cortes ...") },
                            modifier = Modifier.weight(1f), maxLines = 2,
                            isError = hashtags.isNotEmpty() &&
                                (tagCount != 5 || chars > VideoCaptionPolicy.MAX_CHARACTERS))
                        FilledTonalButton(onClick = {
                            runCatching {
                                context.getSystemService(android.content.ClipboardManager::class.java)
                                    .setPrimaryClip(ClipData.newPlainText("Descrição e hashtags",
                                        VideoCaption(description.trim(), hashtags.trim()).combined))
                            }.onSuccess { copied = true; failure = null }
                                .onFailure { failure = "Não foi possível copiar o texto." }
                        }, enabled = captionValid, modifier = Modifier.height(56.dp),
                            contentPadding = PaddingValues(horizontal = 10.dp)) {
                            Icon(if (copied) Icons.Default.Check else Icons.Default.ContentCopy,
                                contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(Modifier.width(4.dp))
                            Text(if (copied) "Copiado" else "Copiar")
                        }
                    }
                    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                        Text("$tagCount/5 hashtags", style = MaterialTheme.typography.labelSmall,
                            color = if (tagCount == 5) MaterialTheme.colorScheme.primary
                                else MaterialTheme.colorScheme.onSurfaceVariant)
                        Text("$chars/100 caracteres", style = MaterialTheme.typography.labelSmall,
                            color = if (chars > 100) MaterialTheme.colorScheme.error
                                else MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                    if (copied) Text("Descrição e hashtags copiadas.",
                        color = MaterialTheme.colorScheme.primary,
                        style = MaterialTheme.typography.labelMedium)
                    if (!captionValid && (description.isNotBlank() || hashtags.isNotBlank())) {
                        Text("Para copiar ou compartilhar o texto: preencha a descrição, use exatamente 5 hashtags diferentes e retire emojis/emoticons; limite de 100 caracteres.",
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            style = MaterialTheme.typography.labelSmall)
                    }
                    if (showTopic) {
                        OutlinedTextField(value = topic, onValueChange = { topic = it.take(280) },
                            label = { Text("Assunto do vídeo para a IA") },
                            placeholder = { Text("Ex.: uma situação engraçada na cozinha") },
                            supportingText = { Text("Somente este texto e as legendas disponíveis poderão ser enviados ao Gemini.") },
                            modifier = Modifier.fillMaxWidth(), maxLines = 3)
                    } else {
                        TextButton(onClick = { showTopic = true }, contentPadding = PaddingValues(0.dp)) {
                            Icon(Icons.Default.Edit, null, Modifier.size(16.dp))
                            Spacer(Modifier.width(5.dp))
                            Text("Complementar o assunto (opcional)")
                        }
                    }
                    Button(onClick = {
                        failure = null
                        if (contextToSend.isBlank()) {
                            showTopic = true
                            failure = "Informe o assunto do vídeo para gerar uma descrição fiel."
                        } else showGeminiConsent = true
                    }, enabled = !generating, modifier = Modifier.fillMaxWidth()) {
                        if (generating) {
                            CircularProgressIndicator(Modifier.size(18.dp), strokeWidth = 2.dp,
                                color = MaterialTheme.colorScheme.onPrimary)
                        } else Icon(Icons.Default.AutoAwesome, null, Modifier.size(18.dp))
                        Spacer(Modifier.width(8.dp))
                        Text(if (generating) "Gerando descrição…"
                            else if (hasGenerated) "Gerar novamente" else "Gerar descrição com IA")
                    }
                    Text("Opcional: você também pode digitar a descrição e as hashtags manualmente. A geração pode consumir cota da API Gemini.",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                }

                if (exportDetails.isNotEmpty()) {
                    OutlinedCard(Modifier.fillMaxWidth()) {
                        TextButton(onClick = { showDetails = !showDetails },
                            modifier = Modifier.fillMaxWidth()) {
                            Icon(Icons.Default.Tune, null, Modifier.size(18.dp))
                            Spacer(Modifier.width(8.dp))
                            Text("Detalhes técnicos", modifier = Modifier.weight(1f))
                            Icon(if (showDetails) Icons.Default.ExpandLess else Icons.Default.ExpandMore,
                                contentDescription = if (showDetails) "Recolher" else "Expandir")
                        }
                        if (showDetails) Column(Modifier.padding(start = 14.dp, end = 14.dp, bottom = 12.dp),
                            verticalArrangement = Arrangement.spacedBy(4.dp)) {
                            exportDetails.forEach { line -> Text(line,
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant) }
                        }
                    }
                }
                failure?.let { Text(it, style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.error) }

                Button(onClick = {
                    runCatching {
                        context.startActivity(Intent.createChooser(Intent(Intent.ACTION_SEND).apply {
                            type = "video/mp4"
                            putExtra(Intent.EXTRA_STREAM, uri)
                            if (captionValid) putExtra(Intent.EXTRA_TEXT,
                                VideoCaption(description.trim(), hashtags.trim()).combined)
                            clipData = ClipData.newUri(context.contentResolver, "Vídeo", uri)
                            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                        }, "Compartilhar vídeo"))
                    }.onFailure { failure = "Não foi possível compartilhar este vídeo." }
                }, modifier = Modifier.fillMaxWidth()) {
                    Icon(Icons.Default.Share, null)
                    Spacer(Modifier.width(8.dp))
                    Text("Compartilhar vídeo")
                }
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    OutlinedButton(onClick = {
                        runCatching {
                            context.startActivity(Intent(Intent.ACTION_VIEW).apply {
                                setDataAndType(uri, "video/mp4")
                                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                            })
                        }.onFailure { failure = "Não há aplicativo disponível para abrir este vídeo." }
                    }, modifier = Modifier.weight(1f)) {
                        Icon(Icons.Default.PlayArrow, null, Modifier.size(18.dp))
                        Spacer(Modifier.width(4.dp))
                        Text("Abrir vídeo", maxLines = 1)
                    }
                    OutlinedButton(onClick = onEdit, modifier = Modifier.weight(1f)) {
                        Text(editLabel, maxLines = 2, overflow = TextOverflow.Ellipsis)
                    }
                }
                TextButton(onClick = onClose, modifier = Modifier.align(Alignment.CenterHorizontally)) {
                    Text("Fechar")
                }
            }
        }
    }
    if (showGeminiConsent) {
        AlertDialog(onDismissRequest = { showGeminiConsent = false },
            title = { Text("Gerar descrição pelo Gemini?") },
            text = { Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("Somente o texto abaixo será enviado ao Google Gemini. O MP4, as imagens e o áudio não serão enviados. A chamada pode consumir sua cota.")
                Column(Modifier.heightIn(max = 220.dp).verticalScroll(rememberScrollState())) {
                    Text(contextToSend, style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                }
            } },
            confirmButton = { TextButton(onClick = {
                showGeminiConsent = false
                generating = true
                failure = null
                scope.launch {
                    try {
                        val key = withContext(Dispatchers.IO) {
                            GeminiCredentialStore(context).read()
                        } ?: throw IOException("Configure sua chave Gemini em Configurações antes de gerar.")
                        val result = generator.generate(key, contextToSend)
                        description = result.description
                        hashtags = result.hashtags
                        copied = false
                        hasGenerated = true
                    } catch (cancelled: CancellationException) {
                        throw cancelled
                    } catch (error: Exception) {
                        failure = if (error is IOException || error is IllegalStateException)
                            error.message ?: "Falha na geração." else "Não foi possível gerar a descrição."
                    } finally { generating = false }
                }
            }) { Text("Autorizar geração") } },
            dismissButton = { TextButton(onClick = { showGeminiConsent = false }) { Text("Cancelar") } })
    }
}
