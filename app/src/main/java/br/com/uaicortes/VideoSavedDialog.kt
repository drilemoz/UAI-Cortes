package br.com.uaicortes

import android.content.ClipData
import android.content.Intent
import android.graphics.Bitmap
import android.net.Uri
import android.os.Build
import android.util.Size
import androidx.compose.foundation.Image
import androidx.compose.foundation.background
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.TextOverflow
import androidx.compose.ui.unit.dp
import androidx.compose.ui.window.Dialog
import androidx.compose.ui.window.DialogProperties
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.NonCancellable
import kotlinx.coroutines.launch
import kotlinx.coroutines.delay
import kotlinx.coroutines.withContext
import java.io.IOException

/** Vídeo salvo no MediaStore: publicação opcional, sem modificar o arquivo exportado. */
@Composable
internal fun VideoSavedDialog(
    uri: Uri, name: String, editLabel: String,
    exportDetails: List<String> = emptyList(),
    qualityReport: ExportQualityReport? = null,
    videoContext: String = "",
    initialPublicationDraft: VideoPublicationDraft? = null,
    onPublicationDraftSave: ((VideoPublicationDraft) -> Boolean)? = null,
    onSocialPublish: ((Uri, String, VideoPublicationDraft) -> Unit)? = null,
    onEdit: (VideoPublicationDraft) -> Unit, onClose: () -> Unit
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val generator = remember(uri) { GeminiVideoCaptionClient(context) }
    val captionPrefs = remember(context) {
        context.applicationContext.getSharedPreferences("caption_model_preferences", android.content.Context.MODE_PRIVATE)
    }
    DisposableEffect(generator) { onDispose { generator.cancel() } }
    var failure by remember(uri) { mutableStateOf<String?>(null) }
    var usageInfo by remember(uri) { mutableStateOf("") }
    var description by remember(uri) { mutableStateOf(initialPublicationDraft?.description.orEmpty()) }
    var hashtags by remember(uri) { mutableStateOf(initialPublicationDraft?.hashtags.orEmpty()) }
    var savedDraft by remember(uri) { mutableStateOf(initialPublicationDraft ?: VideoPublicationDraft()) }
    val onSaveLatest by rememberUpdatedState(onPublicationDraftSave)
    var draftSaveError by remember(uri) { mutableStateOf(false) }
    fun currentDraft() = VideoPublicationDraft(description, hashtags)
    fun persistDraft(): Boolean {
        val draft = currentDraft()
        if (draft == savedDraft || onSaveLatest == null) return true
        val success = runCatching { onSaveLatest?.invoke(draft) == true }.getOrDefault(false)
        if (success) savedDraft = draft
        draftSaveError = !success
        return success
    }
    LaunchedEffect(uri, description, hashtags) {
        if (currentDraft() != savedDraft && onSaveLatest != null) {
            delay(650)
            persistDraft()
        }
    }
    var topic by remember(uri) { mutableStateOf("") }
    var showTopic by remember(uri) { mutableStateOf(videoContext.isBlank()) }
    var showDetails by remember(uri) { mutableStateOf(false) }
    var showGeminiConsent by remember(uri) { mutableStateOf(false) }
    var countedInput by remember(uri) { mutableStateOf<String?>(null) }
    var countingInput by remember(uri) { mutableStateOf(false) }
    var generating by remember(uri) { mutableStateOf(false) }
    var hasGenerated by remember(uri) { mutableStateOf(false) }
    var copied by remember(uri) { mutableStateOf(false) }
    var selectedModel by remember(uri) { mutableStateOf(
        GeminiCaptionModelPolicy.selectedOrDefault(captionPrefs.getString("model", null))) }
    var availableModels by remember(uri) { mutableStateOf<List<GeminiCaptionModel>>(emptyList()) }
    var modelsLoading by remember(uri) { mutableStateOf(false) }
    var modelMenuExpanded by remember(uri) { mutableStateOf(false) }

    val displayedName = remember(uri, name) {
        if (name.isNotBlank()) name else runCatching {
            context.contentResolver.query(uri,
                arrayOf(android.provider.MediaStore.MediaColumns.DISPLAY_NAME), null, null, null)
                ?.use { cursor -> if (cursor.moveToFirst()) cursor.getString(0) else null }
        }.getOrNull() ?: "UaiCortes_Animado.mp4"
    }
    val thumbnail by produceState<Bitmap?>(null, uri) {
        value = withContext(Dispatchers.IO) {
            if (Build.VERSION.SDK_INT >= 29) runCatching {
                context.contentResolver.loadThumbnail(uri, Size(320, 180), null)
            }.getOrNull() else null
        }
    }
    val chars = VideoCaptionPolicy.totalCharacters(description, hashtags)
    val tagCount = VideoCaptionPolicy.hashtagCount(hashtags)
    val captionValid = VideoCaptionPolicy.isValid(description, hashtags)
    // O conteúdo do vídeo não é lido pela IA: somente o texto mostrado ao usuário.
    val contextToSend = remember(videoContext, topic) {
        listOf(videoContext.trim().take(900), topic.trim().take(280))
            .filter { it.isNotBlank() }.joinToString("\n")
    }
    val descriptionCheckpoint = remember(uri) {
        GeminiTaskCheckpointStore(context, GeminiTaskKind.DESCRICAO, uri.toString())
    }
    val descriptionFingerprint = remember(contextToSend, selectedModel) {
        GeminiTaskRecoveryPolicy.digest("$selectedModel\n$contextToSend")
    }
    var savedDescriptionTask by remember(uri) { mutableStateOf<GeminiTaskCheckpoint?>(null) }
    LaunchedEffect(uri, descriptionFingerprint) {
        savedDescriptionTask = withContext(Dispatchers.IO) {
            runCatching { descriptionCheckpoint.load(descriptionFingerprint) }.getOrNull()
        }
    }

    var showCaptionDialog by remember(uri) { mutableStateOf(false) }
    var showAiOptions by remember(uri) { mutableStateOf(false) }
    // O vídeo já foi salvo: a tela principal só mostra ações. A edição de
    // descrição/hashtags e seleção de modelos passa a ficar num diálogo independente.
    Dialog(onDismissRequest = { if (persistDraft()) onClose() },
        properties = DialogProperties(usePlatformDefaultWidth = false)) {
        Surface(Modifier.fillMaxSize(), color = MaterialTheme.colorScheme.background) {
            Column(Modifier.fillMaxSize().statusBarsPadding().navigationBarsPadding()
                .padding(horizontal = 18.dp, vertical = 14.dp)) {
                Column(Modifier.weight(1f).verticalScroll(rememberScrollState()),
                    verticalArrangement = Arrangement.spacedBy(14.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                    Icon(Icons.Default.CheckCircle, null, Modifier.size(46.dp),
                        tint = MaterialTheme.colorScheme.primary)
                    Column {
                        Text("Vídeo salvo!", style = MaterialTheme.typography.headlineSmall,
                            fontWeight = FontWeight.Bold)
                        Text("Disponível na galeria do celular",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }

                Card(Modifier.fillMaxWidth()) {
                    Row(Modifier.padding(12.dp), horizontalArrangement = Arrangement.spacedBy(12.dp),
                        verticalAlignment = Alignment.CenterVertically) {
                        Box(Modifier.size(width = 104.dp, height = 76.dp)
                            .clip(RoundedCornerShape(10.dp))
                            .background(MaterialTheme.colorScheme.surfaceVariant),
                            contentAlignment = Alignment.Center) {
                            if (thumbnail != null) {
                                Image(thumbnail!!.asImageBitmap(), contentDescription = "Miniatura do vídeo salvo",
                                    modifier = Modifier.fillMaxSize(), contentScale = ContentScale.Crop)
                            } else Icon(Icons.Default.Movie, null, Modifier.size(36.dp),
                                tint = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                        Column(Modifier.weight(1f), verticalArrangement = Arrangement.spacedBy(3.dp)) {
                            Text(displayedName, style = MaterialTheme.typography.titleSmall,
                                fontWeight = FontWeight.SemiBold, maxLines = 2,
                                overflow = TextOverflow.Ellipsis)
                            qualityReport?.let { report ->
                                Text(report.resolution + " · " + report.fileSize,
                                    style = MaterialTheme.typography.bodySmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant)
                                if (report.averageFps != "Não informado")
                                    Text("Quadros: ${report.averageFps}",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                            } ?: Text("Arquivo MP4", style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                    }
                    Row(Modifier.padding(start = 12.dp, end = 12.dp, bottom = 10.dp),
                        verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Default.Folder, null, Modifier.size(16.dp),
                            tint = MaterialTheme.colorScheme.onSurfaceVariant)
                        Spacer(Modifier.width(5.dp))
                        Text("Galeria / Filmes/UaiCortes",
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                }


                Spacer(Modifier.height(4.dp))
                Text("Pronto para publicar", style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.SemiBold)
                Text("Escolha uma ação. Descrição e hashtags ficam em uma janela própria.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant)
                if (exportDetails.isNotEmpty()) {
                    OutlinedCard(Modifier.fillMaxWidth()) {
                        TextButton(onClick = { showDetails = !showDetails },
                            modifier = Modifier.fillMaxWidth()) {
                            Icon(Icons.Default.Tune, null, Modifier.size(18.dp))
                            Spacer(Modifier.width(8.dp))
                            Text("Detalhes técnicos", modifier = Modifier.weight(1f))
                            Icon(if (showDetails) Icons.Default.ExpandLess else Icons.Default.ExpandMore,
                                contentDescription = if (showDetails) "Recolher" else "Expandir")
                        }
                        if (showDetails) Column(Modifier.padding(start = 14.dp, end = 14.dp, bottom = 12.dp),
                            verticalArrangement = Arrangement.spacedBy(4.dp)) {
                            exportDetails.forEach { line -> Text(line,
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant) }
                        }
                    }
                }

                if (usageInfo.isNotBlank()) Text(usageInfo,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant)
                failure?.let { Text(it, color = MaterialTheme.colorScheme.error,
                    style = MaterialTheme.typography.bodySmall) }
                }
                Spacer(Modifier.height(10.dp))
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(7.dp)) {
                    OutlinedCard(onClick = {
                        showAiOptions = false
                        showCaptionDialog = true
                    }, modifier = Modifier.weight(1f), shape = RoundedCornerShape(10.dp)) {
                        Column(Modifier.fillMaxWidth().height(78.dp),
                            verticalArrangement = Arrangement.Center,
                            horizontalAlignment = Alignment.CenterHorizontally) {
                            Icon(Icons.Default.Description, null, Modifier.size(25.dp),
                                tint = MaterialTheme.colorScheme.primary)
                            Spacer(Modifier.height(4.dp))
                            Text("Gerar descrição", style = MaterialTheme.typography.labelSmall,
                                maxLines = 1, overflow = TextOverflow.Ellipsis)
                        }
                    }
                    OutlinedCard(onClick = {
                        showAiOptions = true
                        showCaptionDialog = true
                    }, modifier = Modifier.weight(1f), shape = RoundedCornerShape(10.dp)) {
                        Column(Modifier.fillMaxWidth().height(78.dp),
                            verticalArrangement = Arrangement.Center,
                            horizontalAlignment = Alignment.CenterHorizontally) {
                            Icon(Icons.Default.AutoAwesome, null, Modifier.size(25.dp),
                                tint = MaterialTheme.colorScheme.primary)
                            Spacer(Modifier.height(4.dp))
                            Text("Gerar com IA", style = MaterialTheme.typography.labelSmall,
                                maxLines = 1, overflow = TextOverflow.Ellipsis)
                        }
                    }
                    Card(onClick = {
                    runCatching {
                        context.startActivity(Intent.createChooser(Intent(Intent.ACTION_SEND).apply {
                            type = "video/mp4"
                            putExtra(Intent.EXTRA_STREAM, uri)
                            if (captionValid) putExtra(Intent.EXTRA_TEXT,
                                VideoCaption(description.trim(), hashtags.trim()).combined)
                            clipData = ClipData.newUri(context.contentResolver, "Vídeo", uri)
                            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                        }, "Compartilhar vídeo"))
                    }.onFailure { failure = "Não foi possível compartilhar este vídeo." }

                    }, modifier = Modifier.weight(1f),
                        shape = RoundedCornerShape(10.dp)) {
                        Column(Modifier.fillMaxWidth().height(78.dp),
                            verticalArrangement = Arrangement.Center,
                            horizontalAlignment = Alignment.CenterHorizontally) {
                            Icon(Icons.Default.Share, null, Modifier.size(25.dp),
                                tint = MaterialTheme.colorScheme.primary)
                            Spacer(Modifier.height(4.dp))
                            Text("Compartilhar", style = MaterialTheme.typography.labelSmall,
                                maxLines = 1, overflow = TextOverflow.Ellipsis)
                        }
                    }
                }
                if (onSocialPublish != null) {
                    OutlinedButton(onClick = {
                        if (persistDraft()) onSocialPublish(uri, displayedName, currentDraft())
                    }, modifier = Modifier.fillMaxWidth()) {
                        Icon(Icons.Default.Public, null)
                        Spacer(Modifier.width(8.dp))
                        Text("Publicar nas redes sociais")
                    }
                    Text("Selecione destinos e compartilhe separadamente. A publicação é confirmada por você.",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                }
                Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceEvenly,
                    verticalAlignment = Alignment.CenterVertically) {
                    TextButton(onClick = {
                        runCatching {
                            context.startActivity(Intent(Intent.ACTION_VIEW).apply {
                                setDataAndType(uri, "video/mp4")
                                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                            })
                        }.onFailure { failure = "Não há aplicativo disponível para abrir este vídeo." }
                    }) { Text("Abrir vídeo") }
                    TextButton(onClick = { if (persistDraft()) onEdit(currentDraft()) }) {
                        Text(editLabel, maxLines = 1, overflow = TextOverflow.Ellipsis)
                    }
                    TextButton(onClick = { if (persistDraft()) onClose() }) { Text("Fechar") }
                }
            }
        }
    }
    if (showCaptionDialog) {
        Dialog(onDismissRequest = { if (persistDraft()) showCaptionDialog = false },
            properties = DialogProperties(usePlatformDefaultWidth = false)) {
            Surface(Modifier.fillMaxWidth(.95f).fillMaxHeight(.86f),
                shape = RoundedCornerShape(16.dp),
                color = MaterialTheme.colorScheme.surface) {
                Column(Modifier.fillMaxSize().navigationBarsPadding().padding(14.dp)) {
                    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                        Text("Descrição para publicar", style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.SemiBold, modifier = Modifier.weight(1f))
                        IconButton(onClick = { if (persistDraft()) showCaptionDialog = false }) {
                            Icon(Icons.Default.Close, "Fechar descrição")
                        }
                    }
                    Column(Modifier.weight(1f).verticalScroll(rememberScrollState()),
                        verticalArrangement = Arrangement.spacedBy(10.dp)) {
                Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Descrição na primeira linha e 5 hashtags na segunda. Tudo em até 100 caracteres, sem emojis.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                    OutlinedTextField(value = description,
                        onValueChange = { description = it.take(VideoPublicationDraft.MAX_FIELD_LENGTH); copied = false },
                        label = { Text("Descrição") }, placeholder = { Text("Descreva o vídeo...") },
                        modifier = Modifier.fillMaxWidth(), maxLines = 2,
                        singleLine = false,
                        isError = description.isNotEmpty() &&
                            (chars > VideoCaptionPolicy.MAX_CHARACTERS ||
                                VideoCaptionPolicy.containsEmoticonOrEmoji(description)))
                    Row(verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                        OutlinedTextField(value = hashtags,
                            onValueChange = { hashtags = it.take(VideoPublicationDraft.MAX_FIELD_LENGTH); copied = false },
                            label = { Text("5 hashtags") },
                            placeholder = { Text("#UaiCortes #Cortes ...") },
                            modifier = Modifier.weight(1f), maxLines = 2,
                            isError = hashtags.isNotEmpty() &&
                                (tagCount != 5 || chars > VideoCaptionPolicy.MAX_CHARACTERS))
                        FilledTonalButton(onClick = {
                            runCatching {
                                context.getSystemService(android.content.ClipboardManager::class.java)
                                    .setPrimaryClip(ClipData.newPlainText("Descrição e hashtags",
                                        VideoCaption(description.trim(), hashtags.trim()).combined))
                            }.onSuccess { copied = true; failure = null }
                                .onFailure { failure = "Não foi possível copiar o texto." }
                        }, enabled = captionValid, modifier = Modifier.height(56.dp),
                            contentPadding = PaddingValues(horizontal = 10.dp)) {
                            Icon(if (copied) Icons.Default.Check else Icons.Default.ContentCopy,
                                contentDescription = null, modifier = Modifier.size(18.dp))
                            Spacer(Modifier.width(4.dp))
                            Text(if (copied) "Copiado" else "Copiar")
                        }
                    }
                    Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                        Text("$tagCount/5 hashtags", style = MaterialTheme.typography.labelSmall,
                            color = if (tagCount == 5) MaterialTheme.colorScheme.primary
                                else MaterialTheme.colorScheme.onSurfaceVariant)
                        Text("$chars/100 caracteres", style = MaterialTheme.typography.labelSmall,
                            color = if (chars > 100) MaterialTheme.colorScheme.error
                                else MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                    if (draftSaveError) Text("Não foi possível salvar o rascunho no projeto. Tente novamente antes de sair.",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.error)
                    if (onPublicationDraftSave != null) Text(
                        if (currentDraft() == savedDraft) "Rascunho salvo no projeto."
                        else "Alterações pendentes; salvamento automático em instantes.",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                    if (copied) Text("Descrição e hashtags copiadas.",
                        color = MaterialTheme.colorScheme.primary,
                        style = MaterialTheme.typography.labelMedium)
                    if (!captionValid && (description.isNotBlank() || hashtags.isNotBlank())) {
                        Text("Para copiar ou compartilhar o texto: preencha a descrição, use exatamente 5 hashtags diferentes e retire emojis/emoticons; limite de 100 caracteres.",
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                            style = MaterialTheme.typography.labelSmall)
                    }
                    if (showAiOptions) {
                    if (showTopic) {
                        OutlinedTextField(value = topic, onValueChange = { topic = it.take(280) },
                            label = { Text("Assunto do vídeo para a IA") },
                            placeholder = { Text("Ex.: uma situação engraçada na cozinha") },
                            supportingText = { Text("Somente este texto e as legendas disponíveis poderão ser enviados ao Gemini.") },
                            modifier = Modifier.fillMaxWidth(), maxLines = 3)
                    } else {
                        TextButton(onClick = { showTopic = true }, contentPadding = PaddingValues(0.dp)) {
                            Icon(Icons.Default.Edit, null, Modifier.size(16.dp))
                            Spacer(Modifier.width(5.dp))
                            Text("Complementar o assunto (opcional)")
                        }
                    }
                    OutlinedCard(Modifier.fillMaxWidth()) {
                        Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                            Row(verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.SpaceBetween,
                                modifier = Modifier.fillMaxWidth()) {
                                Text("Modelo Gemini para descrição",
                                    style = MaterialTheme.typography.labelMedium,
                                    modifier = Modifier.weight(1f))
                                TextButton(onClick = {
                                    scope.launch {
                                        modelsLoading = true
                                        failure = null
                                        try {
                                            val key = withContext(Dispatchers.IO) {
                                                GeminiCredentialStore(context).read()
                                            } ?: throw IOException("Configure sua chave Gemini em Configurações.")
                                            val models = generator.listModels(key)
                                            availableModels = models
                                            if (models.none { it.id == selectedModel }) {
                                                selectedModel = models.first().id
                                                captionPrefs.edit().putString("model", selectedModel).apply()
                                            }
                                        } catch (cancelled: CancellationException) {
                                            throw cancelled
                                        } catch (error: Exception) {
                                            failure = if (error is IOException || error is IllegalStateException)
                                                error.message ?: "Falha na consulta de modelos."
                                            else "Não foi possível consultar os modelos Gemini."
                                        } finally { modelsLoading = false }
                                    }
                                }, enabled = !modelsLoading && !generating,
                                    contentPadding = PaddingValues(horizontal = 4.dp)) {
                                    if (modelsLoading) CircularProgressIndicator(
                                        Modifier.size(15.dp), strokeWidth = 2.dp)
                                    else Icon(Icons.Default.Refresh, null, Modifier.size(16.dp))
                                    Spacer(Modifier.width(4.dp))
                                    Text(if (modelsLoading) "Consultando…" else "Consultar modelos")
                                }
                            }
                            Box(Modifier.fillMaxWidth()) {
                                OutlinedButton(onClick = { modelMenuExpanded = true },
                                    enabled = !modelsLoading && !generating && availableModels.isNotEmpty(),
                                    modifier = Modifier.fillMaxWidth()) {
                                    Text(availableModels.firstOrNull { it.id == selectedModel }?.label
                                        ?: selectedModel,
                                        modifier = Modifier.weight(1f), maxLines = 2,
                                        overflow = TextOverflow.Ellipsis)
                                    Icon(Icons.Default.ArrowDropDown, "Escolher modelo")
                                }
                                DropdownMenu(expanded = modelMenuExpanded && availableModels.isNotEmpty(),
                                    onDismissRequest = { modelMenuExpanded = false }) {
                                    availableModels.forEach { item ->
                                        DropdownMenuItem(text = { Text(item.label, maxLines = 2) },
                                            onClick = {
                                                selectedModel = item.id
                                                captionPrefs.edit().putString("model", item.id).apply()
                                                modelMenuExpanded = false
                                            })
                                    }
                                }
                            }
                            Text(if (availableModels.isEmpty())
                                "Modelo salvo ou padrão. Consulte para ver os modelos que sua chave oferece."
                                else "${availableModels.size} modelos com suporte a generateContent listados. A geração confirma a compatibilidade JSON.",
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                    }
                    Button(onClick = {
                        failure = null
                        if (contextToSend.isBlank()) {
                            showTopic = true
                            failure = "Informe o assunto do vídeo para gerar uma descrição fiel."
                        } else {
                            countedInput = null
                            showGeminiConsent = true
                        }
                    }, enabled = !generating && !modelsLoading, modifier = Modifier.fillMaxWidth()) {
                        if (generating) {
                            CircularProgressIndicator(Modifier.size(18.dp), strokeWidth = 2.dp,
                                color = MaterialTheme.colorScheme.onPrimary)
                        } else Icon(Icons.Default.AutoAwesome, null, Modifier.size(18.dp))
                        Spacer(Modifier.width(8.dp))
                        Text(if (generating) "Gerando descrição…"
                            else if (hasGenerated) "Gerar novamente" else "Gerar descrição com IA")
                    }
                    Text("Opcional: você também pode digitar a descrição e as hashtags manualmente. A geração pode consumir cota da API Gemini.",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                    } else {
                        TextButton(onClick = { showAiOptions = true }) {
                            Icon(Icons.Default.AutoAwesome, null, Modifier.size(18.dp))
                            Spacer(Modifier.width(6.dp))
                            Text("Gerar com IA")
                        }
                    }
                }


                        savedDescriptionTask?.let { checkpoint ->
                            Surface(shape = RoundedCornerShape(9.dp),
                                color = MaterialTheme.colorScheme.surfaceVariant) {
                                Column(Modifier.fillMaxWidth().padding(9.dp),
                                    verticalArrangement = Arrangement.spacedBy(4.dp)) {
                                    Text(if (checkpoint.stage == GeminiTaskStage.READY)
                                        "Descrição anterior recuperável localmente, sem Gemini."
                                    else "Uma geração anterior foi interrompida. Repetir pode consumir cota.",
                                        style = MaterialTheme.typography.bodySmall)
                                    Row(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                                        if (checkpoint.stage == GeminiTaskStage.READY)
                                            TextButton(onClick = { scope.launch {
                                                val recovered = withContext(Dispatchers.IO) {
                                                    runCatching { descriptionCheckpoint.load(descriptionFingerprint)
                                                        ?.let(descriptionCheckpoint::description) }.getOrNull()
                                                }
                                                if (recovered != null) {
                                                    description = recovered.description
                                                    hashtags = recovered.hashtags
                                                    failure = if (persistDraft()) null
                                                        else "Não foi possível salvar o rascunho recuperado."
                                                } else failure = "Rascunho recuperável indisponível."
                                            } }) { Text("Restaurar") }
                                        TextButton(onClick = { scope.launch {
                                            withContext(Dispatchers.IO) {
                                                runCatching { descriptionCheckpoint.clear() }
                                            }
                                            savedDescriptionTask = null
                                        } }) { Text("Descartar") }
                                    }
                                }
                            }
                        }
                        if (usageInfo.isNotBlank()) Text(usageInfo,
                            style = MaterialTheme.typography.labelSmall)
                        failure?.let { Text(it, color = MaterialTheme.colorScheme.error,
                            style = MaterialTheme.typography.labelSmall) }
                    }
                    TextButton(onClick = { if (persistDraft()) showCaptionDialog = false },
                        modifier = Modifier.align(Alignment.End)) {
                        Text("Concluir")
                    }
                }
            }
        }
    }
    if (showGeminiConsent) {
        AlertDialog(onDismissRequest = { showGeminiConsent = false },
            title = { Text("Gerar descrição pelo Gemini?") },
            text = { Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("Modelo: $selectedModel. Somente o texto abaixo será enviado ao Google Gemini. O MP4, as imagens e o áudio não serão enviados. A chamada pode consumir sua cota.")
                Column(Modifier.heightIn(max = 220.dp).verticalScroll(rememberScrollState())) {
                    Text(contextToSend, style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant)
                }
                GeminiUsageHint("descrição e hashtags", contextToSend.length, model = selectedModel)
                OutlinedButton(onClick = {
                    countingInput = true
                    countedInput = "Consultando entrada no Gemini…"
                    scope.launch {
                        try {
                            val key = withContext(Dispatchers.IO) { GeminiCredentialStore(context).read() }
                                ?: throw IOException("Configure uma chave Gemini.")
                            val tokens = generator.countCaptionInput(key, contextToSend, selectedModel)
                            countedInput = "$tokens tokens de entrada contados pelo Gemini. A resposta será adicional."
                        } catch (cancelled: CancellationException) { throw cancelled }
                        catch (_: Exception) { countedInput = "Contagem indisponível; você ainda pode gerar." }
                        finally { countingInput = false }
                    }
                }, enabled = !countingInput && !generating) { Text("Conferir tokens de entrada") }
                countedInput?.let { Text(it, style = MaterialTheme.typography.bodySmall) }
            } },
            confirmButton = { TextButton(onClick = {
                showGeminiConsent = false
                generating = true
                failure = null
                scope.launch {
                    var geminiStarted = false
                    try {
                        val key = withContext(Dispatchers.IO) {
                            GeminiCredentialStore(context).read()
                        } ?: throw IOException("Configure sua chave Gemini em Configurações antes de gerar.")
                        withContext(Dispatchers.IO) {
                            descriptionCheckpoint.start(descriptionFingerprint, selectedModel)
                        }
                        savedDescriptionTask = null
                        geminiStarted = true
                        val result = generator.generate(key, contextToSend, selectedModel)
                        withContext(Dispatchers.IO) {
                            descriptionCheckpoint.saveDescription(descriptionFingerprint, selectedModel,
                                VideoPublicationDraft(result.description, result.hashtags))
                        }
                        savedDescriptionTask = GeminiTaskCheckpoint(descriptionFingerprint, selectedModel,
                            GeminiTaskStage.READY, System.currentTimeMillis())
                        description = result.description
                        hashtags = result.hashtags
                        copied = false
                        hasGenerated = true
                        usageInfo = GeminiUsageLedger(context).lastMessage("descricao")
                        if (!persistDraft()) failure = "Descrição gerada e preservada localmente, " +
                            "mas o projeto não pôde ser salvo."
                    } catch (cancelled: CancellationException) {
                        if (geminiStarted) withContext(NonCancellable + Dispatchers.IO) {
                            runCatching { descriptionCheckpoint.review(descriptionFingerprint, selectedModel) }
                        }
                        throw cancelled
                    } catch (error: Exception) {
                        if (geminiStarted) {
                            withContext(NonCancellable + Dispatchers.IO) {
                                runCatching { descriptionCheckpoint.review(descriptionFingerprint, selectedModel) }
                            }
                            savedDescriptionTask = GeminiTaskCheckpoint(descriptionFingerprint, selectedModel,
                                GeminiTaskStage.REVIEW, System.currentTimeMillis())
                        }
                        failure = GeminiOperationFailure.label(GeminiOperationFailure.fromThrowable(error))
                    } finally { generating = false }
                }
            }, enabled = !countingInput) { Text("Autorizar geração") } },
            dismissButton = { TextButton(onClick = { showGeminiConsent = false }) { Text("Cancelar") } })
    }
}
